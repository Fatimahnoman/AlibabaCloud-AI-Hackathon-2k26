// =================================================================
// SEED FUNCTION
// =================================================================
async function main() {
  console.log('Seeding scholarships...');

  // Delete existing
  await prisma.scholarshipRequirement.deleteMany();
  await prisma.scholarship.deleteMany();

  let scholarshipCount = 0;
  let requirementCount = 0;

  for (const s of scholarships) {
    await prisma.scholarship.create({
      data: {
        id: s.id,
        name: s.name,
        provider: s.provider,
        country: s.country,
        amount: s.amount,
        currency: s.currency,
        deadline: s.deadline,
        description: s.description,
        eligibilityCriteria: s.eligibilityCriteria,
        sourceUrl: s.sourceUrl,
        sourceName: s.sourceName,
        verificationStatus: 'verified',
        lastVerifiedAt: new Date(),
        requirements: {
          create: s.requirements.map(r => ({
            requirementType: r.requirementType,
            requirementValue: r.requirementValue,
            isRequired: r.isRequired,
          })),
        },
      },
    });
    scholarshipCount++;
    requirementCount += s.requirements.length;
  }

  console.log(`Seeded ${scholarshipCount} scholarships and ${requirementCount} requirements.`);

  // Count by country
  const pakistan = scholarships.filter(s => s.country === 'Pakistan').length;
  const intl = scholarships.filter(s => s.country !== 'Pakistan').length;
  console.log(`Pakistan: ${pakistan} | International: ${intl}`);
}

main()
  .then(() => prisma.$disconnect())
  .catch(async (e) => {
    console.error(e);
    await prisma.$disconnect();
    process.exit(1);
  });
