async function main() {
  console.log('=== Seeding REAL Scholarship Data ===\n');

  // Clear existing
  const deleted = await p.scholarship.deleteMany();
  console.log(`Cleared ${deleted.count} existing scholarships`);

  // Determine amount frequency based on scholarship characteristics
  function getFrequency(s: typeof scholarships[0]): string {
    const name = s.name.toLowerCase();
    const desc = (s.description || '').toLowerCase();
    // One-time scholarships
    if (name.includes('holland') || name.includes('award') || name.includes('one-time')) return 'one_time';
    // Total/annual amounts (large sums like PKR 2,500,000 or USD 50,000)
    if (s.amount && s.amount >= 10000 && !name.includes('monthly') && !desc.includes('monthly stipend')) {
      // Check if description mentions monthly
      if (desc.includes('/month') || desc.includes('per month') || desc.includes('monthly')) return 'monthly';
      // Large amounts are usually total/annual
      if ((s.currency === 'PKR' && s.amount >= 25000) || (s.currency === 'USD' && s.amount >= 5000) || (s.currency === 'GBP' && s.amount >= 5000) || (s.currency === 'EUR' && s.amount >= 5000)) {
        if (desc.includes('year') || desc.includes('annual')) return 'annual';
        return 'total';
      }
      return 'monthly';
    }
    // Small amounts are typically monthly stipends
    return 'monthly';
  }

  let count = 0;
  for (const s of scholarships) {
    const { requirements, ...scholarshipData } = s;
    const id = scholarshipData.id;
    const frequency = getFrequency(s);

    await p.scholarship.create({
      data: {
        ...scholarshipData,
        amountFrequency: frequency,
        requirements: {
          create: requirements.map((r) => ({
            requirementType: r.requirementType,
            requirementValue: r.requirementValue,
          })),
        },
      },
    });
    count++;
    console.log(`  [${count}] ${s.name} (${s.category === 'local' ? 'Pakistan' : s.country}) [${frequency}]`);
  }

  const total = await p.scholarship.count();
  const localCount = await p.scholarship.count({ where: { category: 'local' } });
  const intlCount = await p.scholarship.count({ where: { category: 'international' } });
  console.log(`\nTotal: ${total} scholarships (${localCount} Pakistan + ${intlCount} International)`);

  await p.$disconnect();
}

main().catch((e) => { console.error(e); process.exit(1); });
